with open('src/replay_frames.cpp', 'r') as f:
    content = f.read()

def check_ids(name, ids):
    print(f"\n--- {name} ---")
    found = []
    missing = []
    for id_hex in ids:
        # Search for {id_hex, in the file, ignoring case
        id_int = int(id_hex, 16)
        pattern = re.compile(rf'\{{\s*(0x0*{id_int:X}|0x0*{id_int:x}|{id_int})\s*,', re.IGNORECASE)
        if pattern.search(content):
            found.append(id_hex)
        else:
            missing.append(id_hex)
    print(f"Found {len(found)}/{len(ids)}:")
    print(", ".join(found))
    print(f"Missing {len(missing)}/{len(ids)}:")
    print(", ".join(missing))

